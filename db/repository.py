def parse_json_safely(data: Any, default: Any = None) -> Any:
    if isinstance(data, (dict, list)):
        return data
    if isinstance(data, str):
        try:
            # Handle markdown code blocks
            clean = data.strip()
            if clean.startswith("```json"):
                clean = clean[7:]
            elif clean.startswith("```"):
                clean = clean[3:]
            if clean.endswith("```"):
                clean = clean[:-3]
            return json.loads(clean.strip())
        except Exception:
            return default if default is not None else {}
    return default if default is not None else {}


def save_schedule_run(
    db: Session,
    proposed_schedule_data: Any,
    audit_verdict_data: Any = None,
    outreach_flyers_text: str = "",
    director_briefing_text: str = "",
    target_month: str = "Upcoming Month",
) -> Schedule:
    """Persists a complete run of the ADK broker pipeline into Cloud SQL."""
    sched_dict = parse_json_safely(proposed_schedule_data, {})
    stops_list = sched_dict.get("schedule", []) if isinstance(sched_dict, dict) else []

    # 1. Create Schedule
    schedule = Schedule(
        county_fips="36005",
        county_name="Bronx County, NY",
        target_month=target_month,
        status="AUDITED",
        summary=sched_dict.get("methodology_note", "Generated by Google ADK Bronx Mobile Care Broker."),
        director_briefing=director_briefing_text or "",
    )
    db.add(schedule)
    db.flush()  # populate schedule.id

    # 2. Add Stops
    created_stops = []
    for stop_data in stops_list:
        subways = stop_data.get("transit_connections", {}).get("subway_lines", [])
        buses = stop_data.get("transit_connections", {}).get("bus_lines", [])
        if isinstance(subways, str):
            subways = [s.strip() for s in subways.split(",") if s.strip()]
        if isinstance(buses, str):
            buses = [b.strip() for b in buses.split(",") if b.strip()]

        stop = ScheduleStop(
            schedule_id=schedule.id,
            saturday_index=stop_data.get("saturday_index", 1),
            saturday_date=str(stop_data.get("saturday_date", "2026-11-07")),
            geo_id=str(stop_data.get("geo_id", "")),
            neighborhood=stop_data.get("neighborhood", "Bronx Community"),
            hpsa_name=stop_data.get("hpsa_designation_zone", "Bronx HPSA"),
            hpsa_score=float(stop_data.get("hpsa_score", 0.0)),
            composite_score=float(stop_data.get("composite_need_score", 0.0)),
            landmark_name=stop_data.get("landmark_name", "Community Center Plaza"),
            street_intersection=stop_data.get("street_intersection", "Grand Concourse"),
            subway_lines=subways,
            bus_lines=buses,
            lat=float(stop_data.get("lat", 40.8448)),
            lon=float(stop_data.get("lon", -73.8648)),
            total_pop=int(stop_data.get("demographics", {}).get("total_pop", 0) or 0),
            pct_uninsured=float(stop_data.get("demographics", {}).get("pct_uninsured", 0.0) or 0.0),
            pct_asthma=float(stop_data.get("demographics", {}).get("pct_asthma", 0.0) or 0.0),
            pct_diabetes=float(stop_data.get("demographics", {}).get("pct_diabetes", 0.0) or 0.0),
            van_setup_mode=stop_data.get("weather_posture", {}).get("posture_mode", "Standard Open-Air Curbside Canopy"),
            clinical_kits=stop_data.get("clinical_kit_allocations", {}),
            weather_forecast=stop_data.get("weather_posture", {}),
            siting_rationale=stop_data.get("clinical_siting_justification", "Identified by ADK race-blind composite model."),
            is_active=True,
        )
        db.add(stop)
        db.flush()
        created_stops.append(stop)

    # 3. Add Audit Log
    audit_dict = parse_json_safely(audit_verdict_data, {})
    if isinstance(audit_dict, dict) and audit_dict:
        audit_log = AuditLog(
            schedule_id=schedule.id,
            iteration_number=int(audit_dict.get("iteration_number", 1)),
            audit_status=str(audit_dict.get("audit_status", "APPROVED")),
            institutional_outliers_detected=audit_dict.get("traps_checked", {}).get("institutional_outliers_detected", []),
            hpsa_diversity_status=audit_dict.get("traps_checked", {}).get("hpsa_diversity", "PASS"),
            demographic_coverage_ratios=audit_dict.get("coverage_ratios_vs_county_baseline", {}),
            violations=audit_dict.get("violations", []),
            auditor_comments=str(audit_dict.get("summary", "Equity audit verified 4 distinct HPSA stops.")),
        )
        db.add(audit_log)

    # 4. Add Outreach Flyers (split or general)
    if outreach_flyers_text:
        # Create an entry per stop or an aggregated flyer
        for stop in created_stops:
            flyer = OutreachFlyer(
                schedule_id=schedule.id,
                stop_id=stop.id,
                saturday_index=stop.saturday_index,
                headline_en=f"Free Bronx Mobile Health Clinic at {stop.landmark_name}",
                body_en=outreach_flyers_text[:2500],
                headline_es=f"Clínica Móvil de Salud Gratuita en {stop.landmark_name}",
                body_es=outreach_flyers_text[:2500],
                sms_en=f"Free Bronx Mobile Clinic this Saturday at {stop.landmark_name}! Free screenings, asthma care & meds. No insurance needed. {stop.street_intersection}.",
                sms_es=f"¡Clínica Móvil de Salud este sábado en {stop.landmark_name}! Exámenes gratis, cuidado de asma y medicina. No se requiere seguro. {stop.street_intersection}.",
                chw_script_en=f"Hi neighbor! The Bronx Mobile Health Van will be parked right at {stop.landmark_name} on {stop.saturday_date} from 9am to 3pm. Everything is free and confidential.",
                chw_script_es=f"¡Hola vecino! La Unidad Móvil de Salud del Bronx estará en {stop.landmark_name} el {stop.saturday_date} de 9am a 3pm. Todo es gratis y confidencial.",
            )
            db.add(flyer)

    db.commit()
    db.refresh(schedule)
    return schedule


def get_current_schedule(db: Session) -> Optional[Schedule]:
    """Retrieve the latest schedule with stops, flyers, and audit logs."""
    return db.query(Schedule).order_by(desc(Schedule.created_at)).first()


def get_schedule_by_id(db: Session, schedule_id: str) -> Optional[Schedule]:
    """Retrieve a specific schedule by ID."""
    return db.query(Schedule).filter(Schedule.id == schedule_id).first()


def record_admin_action(
    db: Session,
    schedule_id: str,
    action_type: str,
    rejection_reason: Optional[str] = None,
    rejection_category: Optional[str] = None,
    stop_id: Optional[str] = None,
    admin_user: str = "admin@bronxhealth.org",
) -> AdminAction:
    """Record an admin approval or denial."""
    schedule = get_schedule_by_id(db, schedule_id)
    if not schedule:
        raise ValueError(f"Schedule {schedule_id} not found.")

    if action_type.upper() == "APPROVE":
        schedule.status = "APPROVED"
    elif action_type.upper() in ("DENY", "REJECT"):
        schedule.status = "REJECTED"

    action = AdminAction(
        schedule_id=schedule_id,
        stop_id=stop_id,
        action_type=action_type.upper(),
        rejection_category=rejection_category,
        rejection_reason=rejection_reason,
        admin_user=admin_user,
    )
    db.add(action)
    db.commit()
    db.refresh(action)
    db.refresh(schedule)
    return action


def get_audit_logs(db: Session, schedule_id: Optional[str] = None) -> List[AuditLog]:
    """Retrieve audit logs."""
    query = db.query(AuditLog)
    if schedule_id:
        query = query.filter(AuditLog.schedule_id == schedule_id)
    return query.order_by(desc(AuditLog.created_at)).all()
